#!/bin/bash
# /etc/rancher/rke2/registries.yaml for the target's nodes: every upstream
# registry is served by TARGET_REGISTRY under the same path (11-push.sh), so
# chart images (nvcr.io/..., docker.io/..., quay.io/...) need no rewriting in
# the Helm values. Warewulf nodes get the same file from the rke2/runai
# overlays (tags rke2_registry, rke2_registry_prefix, rke2_workload_registry);
# other nodes: copy this one, then restart rke2-server / rke2-agent.
#   -> $RUNAI_REPO/secrets/registries.yaml (0600, holds the pull credentials)
. "$(dirname "$0")/../lib/common.sh"
need TARGET_REGISTRY
mkpriv "$SECRETS"
OUT="$SECRETS/registries.yaml"
: "${NODE_REGISTRY_CA_PATH:=/etc/rancher/rke2/registry-ca.crt}"

( umask 077; $PY - "$TARGET_REGISTRY" "$TARGET_REGISTRY_PREFIX" "$TARGET_REGISTRY_USER" "$TARGET_REGISTRY_PASSWORD_FILE" \
    "$TARGET_WORKLOAD_REGISTRY" "$TARGET_WORKLOAD_PULL_USER" "$TARGET_WORKLOAD_PULL_PASSWORD_FILE" \
    "$([ -n "$TARGET_REGISTRY_CA" ] && echo "$NODE_REGISTRY_CA_PATH")" > "$OUT" <<'EOF'
import copy, sys, yaml
reg, prefix, user, pwfile, wl, wl_user, wl_pwfile, ca = sys.argv[1:9]
mirror = {"endpoint": [f"https://{reg}"]}
if prefix:
    mirror["rewrite"] = {"^(.*)$": f"{prefix}/$1"}
mirrors = {"docker.io": copy.deepcopy(mirror)}
configs = {}
def cfg(host, u, f):
    c = {}
    if u:
        c["auth"] = {"username": u, "password": open(f).read().strip()}
    if ca:
        c["tls"] = {"ca_file": ca}
    if c:
        configs[host] = c
cfg(reg, user, pwfile)
if wl and wl != reg:
    # own endpoint and account, or "*" would send its pulls to TARGET_REGISTRY
    mirrors[wl] = {"endpoint": [f"https://{wl}"]}
    cfg(wl, wl_user, wl_pwfile)
mirrors["*"] = mirror
print("# Generated by rke2_deploy_ww local/steps/12-registries.sh")
print(yaml.safe_dump({"mirrors": mirrors, "configs": configs}, sort_keys=False).rstrip())
EOF
)
say "wrote $OUT (contains credentials)"
[ -n "$TARGET_REGISTRY_CA" ] && say "nodes also need $TARGET_REGISTRY_CA at $NODE_REGISTRY_CA_PATH"
sed -E 's/(password: ).*/\1********/' "$OUT"
